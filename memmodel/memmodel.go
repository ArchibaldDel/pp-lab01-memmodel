// только sync/atomic, как того требует задание.
package memmodel

// CacheLineSize — размер строки кэша на x86-64 и на ARM64 (64 байта).
// Используется для разнесения полей, которые пишут разные горутины, по
// разным строкам, чтобы избежать ложного разделения (false sharing).
const CacheLineSize = 64

// nextPow2 округляет n вверх до ближайшей степени двойки; nextPow2(0) == 1.
func nextPow2(n uint64) uint64 {
	if n <= 1 {
		return 1
	}
	p := uint64(1)
	for p < n {
		p <<= 1
	}
	return p
}
